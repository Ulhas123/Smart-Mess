const pattern = [
  "111111101010101111111",
  "100000101110101000001",
  "101110100010101011101",
  "101110101111101011101",
  "101110100100101011101",
  "100000101011101000001",
  "111111101010101111111",
  "000000001101100000000",
  "110101111010111101011",
  "001011001111001011100",
  "111001111001111001011",
  "010110001110001110010",
  "101011111011111010111",
  "000000001100101010100",
  "111111101011111011101",
  "100000101110001010010",
  "101110101011111111111",
  "101110100100001011000",
  "101110101111111010111",
  "100000100010101110010",
  "111111101101111011101",
]

export function QRCode({ light = false }: { light?: boolean }) {
  return (
    <div
      className={`qr-code ${light ? "qr-light" : ""}`}
      aria-label="Prototype meal session QR code"
    >
      {pattern.flatMap((row, y) =>
        row
          .split("")
          .map((cell, x) => (
            <span
              key={`${x}-${y}`}
              className={cell === "1" ? "qr-on" : "qr-off"}
            />
          )),
      )}
    </div>
  )
}
